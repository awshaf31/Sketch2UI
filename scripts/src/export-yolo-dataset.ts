/**
 * Export manually-annotated sketches from the API's store into a YOLO dataset.
 *
 * Plan references: section 22.1 (annotate -> validate -> export -> quality-check),
 * section 9.7 (split policy), section 51 step 7 (build the YOLO dataset).
 *
 * This is a standalone build-time tool. It reads apps/api's persisted store file
 * directly rather than importing the API's db module, so it stays entirely out of
 * the API's request path and carries no runtime coupling to apps/api or
 * services/cv-worker (that integration is step 9).
 *
 * Usage:
 *   npm run export:dataset            # write the dataset
 *   npm run export:dataset -- --clean # wipe existing split dirs first
 *   npm run export:dataset -- --dry-run
 */

import fs from "node:fs";
import path from "node:path";
import type { Detection, ProjectAsset, TrainingSample } from "@sketch2ui/shared-types";
import {
  CLASSES_FILE,
  CLASS_INDEX,
  CORRECTION_PREFIX,
  CLASS_LIST,
  DATASET_DIR,
  DATA_YAML,
  SPLITS,
  STORE_FILE,
  UPLOADS_DIR,
  imagesDir,
  isCorrectionFile,
  isExternalFile,
  labelsDir,
  splitForAsset,
  tallyDatasetOnDisk,
  type Split,
} from "./dataset-layout.js";

interface StoreShape {
  assets: ProjectAsset[];
  detections: Detection[];
  trainingSamples: TrainingSample[];
}

interface ExportStats {
  images: Record<Split, number>;
  labels: number;
  perClass: Map<string, number>;
  skippedClassNames: Map<string, number>;
  assetsWithoutLabels: string[];
  missingImageFiles: string[];
  invalidBoxes: number;
  correctionImages: number;
  correctionLabels: number;
  supersededAssets: number;
}

const args = new Set(process.argv.slice(2));
const DRY_RUN = args.has("--dry-run");
const CLEAN = args.has("--clean");

function readStore(): StoreShape {
  if (!fs.existsSync(STORE_FILE)) {
    console.error(`No store file at ${STORE_FILE}.`);
    console.error("Start the API and annotate at least one sketch first.");
    process.exit(1);
  }
  const raw = JSON.parse(fs.readFileSync(STORE_FILE, "utf-8"));
  return {
    assets: raw.assets ?? [],
    detections: raw.detections ?? [],
    trainingSamples: raw.trainingSamples ?? [],
  };
}

/**
 * classes.txt is generated from the taxonomy, but its order is the label-file
 * contract (section 22.6 requires the class list be stored with the dataset). If it
 * already exists and disagrees with the taxonomy, every previously written label file
 * is now wrong, so refuse to continue rather than corrupt the dataset silently.
 */
function verifyOrWriteClassesFile(): void {
  const expected = CLASS_LIST.join("\n") + "\n";

  if (fs.existsSync(CLASSES_FILE)) {
    const actual = fs.readFileSync(CLASSES_FILE, "utf-8");
    if (actual === expected) return;

    const actualList = actual.trim().split("\n");
    console.error("\nclasses.txt does not match ALL_CLASSES in taxonomy.ts.");
    console.error("Class ids are positional, so existing label files would be misread.\n");

    const maxLen = Math.max(actualList.length, CLASS_LIST.length);
    for (let i = 0; i < maxLen; i += 1) {
      if (actualList[i] !== CLASS_LIST[i]) {
        console.error(`  id ${i}: classes.txt=${actualList[i] ?? "(none)"} taxonomy=${CLASS_LIST[i] ?? "(none)"}`);
      }
    }
    console.error(
      "\nIf you intentionally added classes, append them to the END of ALL_CLASSES,"
    );
    console.error("then delete classes.txt and re-export. Never reorder existing entries.\n");
    process.exit(1);
  }

  if (!DRY_RUN) {
    fs.mkdirSync(DATASET_DIR, { recursive: true });
    fs.writeFileSync(CLASSES_FILE, expected);
  }
  console.log(`Wrote classes.txt (${CLASS_LIST.length} classes)`);
}

function writeDataYaml(): void {
  const names = CLASS_LIST.map((name, index) => `  ${index}: ${name}`).join("\n");
  const content = `# Sketch2UI YOLO dataset — generated by scripts/src/export-yolo-dataset.ts
# Class ids are positional and frozen. See ml/dataset/README.md before editing.

path: ${DATASET_DIR}
train: images/train
val: images/val
test: images/test

nc: ${CLASS_LIST.length}
names:
${names}
`;
  if (!DRY_RUN) fs.writeFileSync(DATA_YAML, content);
  console.log(`Wrote data.yaml (nc=${CLASS_LIST.length})`);
}

/** YOLO wants class_id + center-x/center-y/w/h, all normalized. BBox is already
 *  normalized but top-left origin, so only the origin shift is needed. */
function toYoloLine(classId: number, detection: Detection): string | null {
  const { x, y, width, height } = detection.bbox;

  if (!Number.isFinite(x) || !Number.isFinite(y) || !Number.isFinite(width) || !Number.isFinite(height)) {
    return null;
  }
  if (width <= 0 || height <= 0) return null;

  const cx = x + width / 2;
  const cy = y + height / 2;

  // Clamp rather than drop: a box drawn a hair past the image edge is a real
  // annotation, and YOLO requires every value inside [0, 1].
  const clamp = (v: number) => Math.min(Math.max(v, 0), 1);
  const values = [clamp(cx), clamp(cy), clamp(width), clamp(height)];

  return `${classId} ${values.map((v) => v.toFixed(6)).join(" ")}`;
}

function emptyStats(): ExportStats {
  return {
    images: { train: 0, val: 0, test: 0 },
    labels: 0,
    perClass: new Map(),
    skippedClassNames: new Map(),
    assetsWithoutLabels: [],
    missingImageFiles: [],
    invalidBoxes: 0,
    correctionImages: 0,
    correctionLabels: 0,
    supersededAssets: 0,
  };
}

function bump(map: Map<string, number>, key: string): void {
  map.set(key, (map.get(key) ?? 0) + 1);
}

/**
 * Remove previously-exported manual labels so re-annotation cannot leave stale files
 * behind. Files written by import-external-datasets.ts are SPARED — this script cannot
 * regenerate them, so deleting them would silently gut the dataset.
 */
function cleanSplitDirs(): void {
  let removed = 0;
  let spared = 0;

  for (const split of SPLITS) {
    for (const dir of [imagesDir(split), labelsDir(split)]) {
      if (!fs.existsSync(dir)) continue;
      for (const entry of fs.readdirSync(dir)) {
        if (entry === ".gitkeep") continue;
        // External files are spared (this script cannot regenerate them). Correction
        // samples ARE regenerated here from the store, so they are cleaned like any
        // other output of this exporter.
        if (isExternalFile(entry) && !isCorrectionFile(entry)) {
          spared += 1;
          continue;
        }
        fs.rmSync(path.join(dir, entry), { force: true });
        removed += 1;
      }
    }
  }

  console.log(`Cleaned ${removed} manual export file(s)`);
  if (spared > 0) {
    console.log(`  kept ${spared} externally-imported file(s) — re-run import:external to refresh them`);
  }
}

/** Delete any previously-written unprefixed export of one asset, across all splits. */
function removeUnprefixedExport(storageKey: string): void {
  if (DRY_RUN) return;
  const parsed = path.parse(storageKey);
  for (const split of SPLITS) {
    for (const file of [
      path.join(imagesDir(split), storageKey),
      path.join(labelsDir(split), `${parsed.name}.txt`),
    ]) {
      if (fs.existsSync(file)) fs.rmSync(file, { force: true });
    }
  }
}

function main(): void {
  console.log(DRY_RUN ? "Sketch2UI dataset export (dry run)\n" : "Sketch2UI dataset export\n");

  verifyOrWriteClassesFile();
  writeDataYaml();

  if (CLEAN && !DRY_RUN) cleanSplitDirs();

  if (!DRY_RUN) {
    for (const split of SPLITS) {
      fs.mkdirSync(imagesDir(split), { recursive: true });
      fs.mkdirSync(labelsDir(split), { recursive: true });
    }
  }

  const store = readStore();
  const stats = emptyStats();

  // Only human-drawn, still-active boxes are ground truth. Model-sourced detections
  // would be self-training on the detector's own output; deleted/rejected ones were
  // explicitly thrown away by the annotator.
  const groundTruth = store.detections.filter(
    (d) => d.status === "active" && d.source === "manual"
  );

  const byAsset = new Map<string, Detection[]>();
  for (const detection of groundTruth) {
    const list = byAsset.get(detection.sourceAssetId);
    if (list) list.push(detection);
    else byAsset.set(detection.sourceAssetId, [detection]);
  }

  // An approved training sample is a human-signed-off snapshot of BOTH manual and
  // model boxes for that asset. It supersedes the plain manual export for the same
  // image — emitting both would put the same picture in the dataset twice with two
  // different label sets.
  const approvedAssetIds = new Set(
    store.trainingSamples.filter((s) => s.approved).map((s) => s.imageAssetId)
  );

  for (const asset of store.assets) {
    if (approvedAssetIds.has(asset.id)) {
      stats.supersededAssets += 1;
      // Skipping the write is not enough: a PREVIOUS export (before this asset was
      // approved) may have already written the unprefixed copy. Left behind, the same
      // image would sit in the dataset twice under two different label sets.
      removeUnprefixedExport(asset.storageKey);
      continue;
    }
    const sourcePath = path.join(UPLOADS_DIR, asset.storageKey);
    if (!fs.existsSync(sourcePath)) {
      stats.missingImageFiles.push(asset.storageKey);
      continue;
    }

    const detections = byAsset.get(asset.id) ?? [];
    const lines: string[] = [];

    for (const detection of detections) {
      const classId = CLASS_INDEX.get(detection.className);
      if (classId === undefined) {
        bump(stats.skippedClassNames, detection.className);
        continue;
      }

      const line = toYoloLine(classId, detection);
      if (line === null) {
        stats.invalidBoxes += 1;
        continue;
      }

      lines.push(line);
      bump(stats.perClass, detection.className);
      stats.labels += 1;
    }

    if (lines.length === 0) {
      // Not an error: section 9.5 wants negative/background images (off-page notes,
      // arrows, measurements) in the dataset with an empty label file. But an asset
      // that was simply never annotated looks identical, so surface it.
      stats.assetsWithoutLabels.push(asset.storageKey);
    }

    const split = splitForAsset(asset.id);
    const stem = path.parse(asset.storageKey).name;
    const ext = path.parse(asset.storageKey).ext;

    if (!DRY_RUN) {
      fs.copyFileSync(sourcePath, path.join(imagesDir(split), `${stem}${ext}`));
      fs.writeFileSync(
        path.join(labelsDir(split), `${stem}.txt`),
        lines.length > 0 ? lines.join("\n") + "\n" : ""
      );
    }

    stats.images[split] += 1;
  }

  exportApprovedSamples(store, stats);
  report(stats);
}

/**
 * Section 36 / FR-11: approved corrections become training data.
 *
 * Boxes come from the SNAPSHOT taken at approval time, not from the live detections
 * table — later edits must not silently rewrite what a human already signed off on.
 * Both manual and model-sourced boxes are included: after correction the approver has
 * vouched for both equally.
 */
function exportApprovedSamples(store: StoreShape, stats: ExportStats): void {
  for (const sample of store.trainingSamples) {
    if (!sample.approved) continue;

    const sourcePath = path.join(UPLOADS_DIR, sample.storageKey);
    if (!fs.existsSync(sourcePath)) {
      stats.missingImageFiles.push(sample.storageKey);
      continue;
    }

    const lines: string[] = [];
    for (const box of sample.boxes) {
      const classId = CLASS_INDEX.get(box.className);
      if (classId === undefined) {
        bump(stats.skippedClassNames, box.className);
        continue;
      }
      const line = toYoloLine(classId, { bbox: box.bbox } as Detection);
      if (line === null) {
        stats.invalidBoxes += 1;
        continue;
      }
      lines.push(line);
      bump(stats.perClass, box.className);
      stats.labels += 1;
      stats.correctionLabels += 1;
    }

    if (lines.length === 0) continue;

    const parsed = path.parse(sample.storageKey);
    const stem = `${CORRECTION_PREFIX}${parsed.name}`;
    const split = sample.datasetSplit;

    if (!DRY_RUN) {
      fs.copyFileSync(sourcePath, path.join(imagesDir(split), `${stem}${parsed.ext}`));
      fs.writeFileSync(path.join(labelsDir(split), `${stem}.txt`), lines.join("\n") + "\n");
    }

    stats.images[split] += 1;
    stats.correctionImages += 1;
  }
}

function report(stats: ExportStats): void {
  const totalImages = SPLITS.reduce((sum, s) => sum + stats.images[s], 0);

  console.log("\n─── Dataset summary ───\n");
  console.log(`Images: ${totalImages}`);
  for (const split of SPLITS) {
    const n = stats.images[split];
    const pct = totalImages > 0 ? ((n / totalImages) * 100).toFixed(0) : "0";
    console.log(`  ${split.padEnd(6)} ${String(n).padStart(4)}  (${pct}%)`);
  }
  if (stats.correctionImages > 0 || stats.supersededAssets > 0) {
    console.log(
      `\nApproved corrections (section 36): ${stats.correctionImages} image(s), ${stats.correctionLabels} label(s)`
    );
    console.log(
      `  ${stats.supersededAssets} asset(s) exported from their approved snapshot instead of raw manual boxes`
    );
  }

  console.log(`\nLabels: ${stats.labels}`);

  // The split warning must judge the whole dataset on disk, not just this run's rows:
  // once external sources are imported, the manual export alone is a small slice of it
  // and would raise a permanent false alarm.
  const merged = tallyDatasetOnDisk();
  const mergedTotal = SPLITS.reduce((sum, s) => sum + merged.images[s], 0);

  if (mergedTotal > totalImages) {
    console.log("\n─── Merged dataset on disk (incl. imported sources) ───\n");
    console.log(`Images: ${mergedTotal}`);
    for (const split of SPLITS) {
      const n = merged.images[split];
      const pct = mergedTotal > 0 ? ((n / mergedTotal) * 100).toFixed(0) : "0";
      console.log(`  ${split.padEnd(6)} ${String(n).padStart(4)}  (${pct}%)`);
    }
    console.log(`Labels: ${merged.labels}`);
    console.log("\nRun `npm run import:external` for the full merged per-class report.");
  }

  const emptySplits = SPLITS.filter((s) => merged.images[s] === 0);
  if (mergedTotal > 0 && emptySplits.length > 0) {
    console.log(
      `\n⚠ Empty split(s): ${emptySplits.join(", ")}. Training needs a non-empty val set.`
    );
    console.log("  The hash split (section 9.7) only approaches 75/15/10 as image count grows —");
    console.log(`  at ${mergedTotal} image(s) it can put everything in one split. Add more sketches.`);
  }

  console.log("\n─── Per-class label counts ───\n");
  const counted = CLASS_LIST.map((name, id) => ({ id, name, count: stats.perClass.get(name) ?? 0 }));
  const present = counted.filter((c) => c.count > 0).sort((a, b) => b.count - a.count);
  const absent = counted.filter((c) => c.count === 0);

  for (const { id, name, count } of present) {
    // Section 9.3: too many visually-similar classes with too little data causes
    // confusion. Flag the thin ones rather than letting them look trained.
    const flag = count === 1 ? "  ⚠ only 1 example" : count < 5 ? "  ⚠ very few" : "";
    console.log(`  ${String(id).padStart(2)}  ${name.padEnd(20)} ${String(count).padStart(4)}${flag}`);
  }

  if (absent.length > 0) {
    console.log(`\n  ${absent.length} class(es) with NO examples:`);
    console.log(`    ${absent.map((c) => c.name).join(", ")}`);
  }

  const thin = present.filter((c) => c.count < 5).length;
  if (thin > 0 || absent.length > 0) {
    console.log(
      `\n  Section 9.3: ${absent.length} unrepresented + ${thin} under-represented class(es).`
    );
    console.log("  Collect more sketches covering these before training (step 8),");
    console.log("  or train on a reduced class set (Appendix K's 25-class starter list).");
  }

  if (stats.skippedClassNames.size > 0) {
    console.log("\n─── Skipped: className not in taxonomy ───\n");
    for (const [name, count] of [...stats.skippedClassNames].sort((a, b) => b[1] - a[1])) {
      console.log(`  ${name.padEnd(24)} ${count}  (add to taxonomy.ts or fix the annotation)`);
    }
  }

  if (stats.invalidBoxes > 0) {
    console.log(`\n⚠ Dropped ${stats.invalidBoxes} box(es) with non-finite or zero-area geometry.`);
  }

  if (stats.missingImageFiles.length > 0) {
    console.log(`\n⚠ ${stats.missingImageFiles.length} asset(s) recorded but missing from data/uploads:`);
    for (const key of stats.missingImageFiles) console.log(`    ${key}`);
  }

  if (stats.assetsWithoutLabels.length > 0) {
    console.log(`\n⚠ ${stats.assetsWithoutLabels.length} image(s) exported with an EMPTY label file:`);
    for (const key of stats.assetsWithoutLabels) console.log(`    ${key}`);
    console.log("  Intentional only if these are section 9.5 background/negative images.");
    console.log("  Otherwise they are un-annotated sketches and will teach the model nothing.");
  }

  if (DRY_RUN) console.log("\n(dry run — nothing written)");
  console.log("");
}

main();
